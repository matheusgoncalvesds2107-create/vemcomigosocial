create table if not exists public.testimonies (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 1500),
  image_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.devotionals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  bible_reference text,
  content text not null check (char_length(content) between 1 and 2500),
  created_at timestamptz not null default now()
);

create table if not exists public.podcast_episodes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  guest text,
  description text,
  audio_url text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.songs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  artist text,
  audio_url text not null,
  created_at timestamptz not null default now()
);

alter table public.testimonies enable row level security;
alter table public.devotionals enable row level security;
alter table public.podcast_episodes enable row level security;
alter table public.songs enable row level security;

-- Testemunhos
create policy "testimonies_read" on public.testimonies for select to authenticated using (true);
create policy "testimonies_insert_own" on public.testimonies for insert to authenticated with check (auth.uid()=user_id);
create policy "testimonies_delete_own" on public.testimonies for delete to authenticated using (auth.uid()=user_id);

-- Palavra
create policy "devotionals_read" on public.devotionals for select to authenticated using (true);
create policy "devotionals_insert_own" on public.devotionals for insert to authenticated with check (auth.uid()=user_id);
create policy "devotionals_delete_own" on public.devotionals for delete to authenticated using (auth.uid()=user_id);

-- Podcast
create policy "podcast_read" on public.podcast_episodes for select to authenticated using (true);
create policy "podcast_insert_own" on public.podcast_episodes for insert to authenticated with check (auth.uid()=user_id);
create policy "podcast_delete_own" on public.podcast_episodes for delete to authenticated using (auth.uid()=user_id);

-- Louvores
create policy "songs_read" on public.songs for select to authenticated using (true);
create policy "songs_insert_own" on public.songs for insert to authenticated with check (auth.uid()=user_id);
create policy "songs_delete_own" on public.songs for delete to authenticated using (auth.uid()=user_id);

-- Bucket único para MP3 de podcasts/louvores
insert into storage.buckets (id,name,public)
values ('media-audio','media-audio',true)
on conflict (id) do update set public=true;

create policy "media_audio_public_read" on storage.objects
for select to public using (bucket_id='media-audio');

create policy "media_audio_upload_own" on storage.objects
for insert to authenticated
with check (bucket_id='media-audio' and (storage.foldername(name))[1]=auth.uid()::text);

create policy "media_audio_delete_own" on storage.objects
for delete to authenticated
using (bucket_id='media-audio' and (storage.foldername(name))[1]=auth.uid()::text);

create index if not exists testimonies_created_idx on public.testimonies(created_at desc);
create index if not exists devotionals_created_idx on public.devotionals(created_at desc);
create index if not exists podcast_created_idx on public.podcast_episodes(created_at desc);
create index if not exists songs_created_idx on public.songs(created_at desc);
